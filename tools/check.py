"""Rule checks for the data and the built pages.

    python tools/check.py

Run it before every commit; CI runs it on every pull request and push.
It exits 1 and prints one line per broken rule. Do not edit this file to make
a failing check pass: fix the data or the screen, or raise it in the PR.

What it checks
  1. Sources: required fields, known kind, https link, no duplicate link.
  2. Every figure has a source, or says why it is missing. Computed figures carry their formula.
     The Latest column has a declared list of year-to-date periods to read from.
  3. Arithmetic: growth rates, margins, segment totals and declared period sums agree with the figures.
  4. News: required fields, known company and type, dated on or before the as-of date, newest first.
     Calendar entries say whether they are earnings dates or other dates.
  5. Share prices: one price or return for every month a share is in the index, a source for
     every series, published returns that agree with the prices, and indexes that compute.
  6. Writing: no banned words, no long quotations, no emoji.
  7. Built pages: no empty slots, balanced tags, unique ids, every internal link resolves.
"""
import pathlib
import re
import sys
from html.parser import HTMLParser

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import model         # noqa: E402
import build_static  # noqa: E402
import stockindex    # noqa: E402

TOL = 0.15  # percentage points allowed between a stated rate and the one recomputed from rounded figures
DATE = re.compile(r"^\d{4}-(0[1-9]|1[0-2])(-(0[1-9]|[12]\d|3[01]))?$")
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
BANNED = [r"\bunlock", r"\bseamless", r"\bsynerg", r"\brobust", r"cutting[- ]edge", r"best[- ]in[- ]class",
          r"world[- ]class", r"game[- ]chang", r"\bleverag(es|ed|ing)\b", r"\bleverage (our|its|their|this|these)\b"]
QUOTED = re.compile(r"[“\"]([^“”\"]{20,})[”\"]")
EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️]")
RESERVED_HASH = {"settings", "sidebar", "customize", "upgrade", "downloads"}
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}

errors, warnings = [], []


def err(msg):
    errors.append(msg)


def num(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


# ---------- 1. sources ----------

def check_sources(d):
    src, kinds = d["sources"]["sources"], d["sources"]["kinds"]
    accessed = d["sources"]["accessed"]
    seen = {}
    for sid, s in src.items():
        w = f"sources.json {sid}"
        if not re.fullmatch(r"[a-z0-9_]+", sid):
            err(f"{w}: id must be lower-case letters, digits and underscores")
        for k in ("title", "publisher", "kind", "url"):
            if not s.get(k):
                err(f"{w}: missing {k}")
        if "date" not in s:
            err(f"{w}: missing date (use null when the page is undated)")
        elif s["date"] is not None and (not DATE.match(s["date"]) or s["date"][:10] > accessed):
            err(f"{w}: date must be YYYY-MM-DD or YYYY-MM, not after {accessed}")
        if s.get("kind") not in kinds:
            err(f"{w}: unknown kind {s.get('kind')!r}")
        if not str(s.get("url", "")).startswith("https://"):
            err(f"{w}: url must start with https://")
        if s.get("url") in seen:
            err(f"{w}: same url as {seen[s['url']]}")
        seen[s.get("url")] = sid
        if bool(s.get("reviewed_by")) != bool(s.get("reviewed_on")):
            err(f"{w}: reviewed_by and reviewed_on go together")
    return src


# ---------- 2 and 3. companies and figures ----------

def need(src, sid, where):
    if sid not in src:
        err(f"{where}: unknown source {sid!r}")


def check_cell(src, cell, where, kind):
    if not isinstance(cell, list) or not 2 <= len(cell) <= 3:
        err(f"{where}: a cell is [value, source] or [value, source, note]")
        return
    v, s = cell[0], cell[1]
    if v is None:
        if s not in model.REASONS:
            err(f"{where}: a missing value needs a reason, one of {sorted(model.REASONS)}")
    elif not num(v):
        err(f"{where}: value must be a number or null")
    elif s == "computed":
        if len(cell) < 3 or not cell[2]:
            err(f"{where}: a computed figure needs its formula as the note")
    else:
        need(src, s, where)


def close(a, b, tol, where, what):
    if abs(a - b) > tol:
        err(f"{where}: {what}: stated {b}, recomputed {a:.2f}")


def check_company(d, cid, src):
    cos, fin = d["companies"]["companies"], d["financials"]
    if cid not in cos or cid not in fin:
        err(f"{cid}: must be in both companies.json and financials.json")
        return
    co, f = cos[cid], fin[cid]
    for k in ("name", "short", "ticker", "listing", "currency", "money_prefix", "unit", "fy_end", "hq", "ceo",
              "ir_url", "description", "profit_measure", "margin_measure", "organic_label"):
        if not co.get(k):
            err(f"companies.json {cid}: missing {k}")
    if co.get("dp") not in (0, 1):
        err(f"companies.json {cid}: dp must be 0 or 1")
    if co.get("margin_family") not in ("operating", "ebitda"):
        err(f"companies.json {cid}: margin_family must be operating or ebitda")
    for s in co.get("profile_sources", []) + (co.get("status") or {}).get("sources", []):
        need(src, s, f"companies.json {cid}")

    # annual
    a = f["annual"]
    cols = a["columns"]
    rows = {}
    for row in a["rows"]:
        w = f"financials.json {cid} annual {row.get('label')!r}"
        if row["key"] in rows:
            err(f"{w}: duplicate key {row['key']}")
        rows[row["key"]] = row
        if row.get("kind") not in model.KINDS:
            err(f"{w}: unknown kind {row.get('kind')!r}")
        if len(row["cells"]) != len(cols):
            err(f"{w}: {len(row['cells'])} cells for {len(cols)} columns")
        for col, cell in zip(cols, row["cells"]):
            check_cell(src, cell, f"{w} {col}", row.get("kind"))
    roles = {r.get("role") for r in a["rows"]}
    for role in ("revenue", "profit", "margin"):
        if role not in roles:
            err(f"financials.json {cid}: annual table needs a row with role {role!r}")
    if a.get("reported") and not DATE.match(a["reported"]):
        err(f"financials.json {cid}: annual.reported must be a date")
    for row in a["rows"]:
        chk, w = row.get("check") or {}, f"financials.json {cid} annual {row['label']!r}"
        vals = [c[0] for c in row["cells"]]
        if "growth_of" in chk:
            base = [c[0] for c in rows[chk["growth_of"]]["cells"]]
            for i in range(1, len(cols)):
                if None not in (vals[i], base[i], base[i - 1]):
                    close((base[i] / base[i - 1] - 1) * 100, vals[i], TOL, f"{w} {cols[i]}", "growth")
        if "margin_of" in chk:
            top = [c[0] for c in rows[chk["margin_of"][0]]["cells"]]
            bottom = [c[0] for c in rows[chk["margin_of"][1]]["cells"]]
            for i in range(len(cols)):
                if None not in (vals[i], top[i], bottom[i]):
                    close(top[i] / bottom[i] * 100, vals[i], TOL, f"{w} {cols[i]}", "margin")

    # interim
    it = f["interim"]
    keys = {m["key"] for m in it["metrics"]}
    for m in it["metrics"]:
        if m.get("kind") not in model.KINDS:
            err(f"financials.json {cid} interim metric {m.get('key')}: unknown kind")
        elif m["key"] in rows and m["kind"] != rows[m["key"]].get("kind"):
            # the Latest column prints an interim value in the annual row that shares its key
            err(f"financials.json {cid} interim metric {m['key']}: kind {m['kind']!r} differs from the annual row "
                f"with the same key ({rows[m['key']].get('kind')!r}); use another key if the measure differs")
    periods = {}
    for p in it["periods"]:
        w = f"financials.json {cid} interim {p.get('label')!r}"
        if p["label"] in periods:
            err(f"{w}: duplicate period")
        periods[p["label"]] = p
        need(src, p.get("src"), w)
        for k in ("end", "reported"):
            if p.get(k) is not None and not DATE.match(str(p.get(k))):
                err(f"{w}: {k} must be a date or null")
        for k, v in p["v"].items():
            if k not in keys:
                err(f"{w}: {k} is not a declared metric")
            if not num(v):
                err(f"{w}: {k} must be a number")
        extra = p.get("extra") or {}
        for k, v in extra.items():
            if k not in rows:
                err(f"{w}: extra.{k} is not the key of an annual row")
            if k in keys:
                err(f"{w}: extra.{k} is an interim metric; put the value in v")
            if not num(v):
                err(f"{w}: extra.{k} must be a number")
        for k, s in (p.get("srcs") or {}).items():
            if k not in p["v"] and k not in extra:
                err(f"{w}: srcs.{k} has no value")
            need(src, s, w)
        for k, formula in (p.get("computed") or {}).items():
            if k not in p["v"] or not formula:
                err(f"{w}: computed.{k} needs a value and a formula")
        v = p["v"]
        if all(k in v for k in ("profit", "revenue", "margin")):
            close(v["profit"] / v["revenue"] * 100, v["margin"], TOL, w, "margin")
    for s in it.get("sums", []):
        for m in s["metrics"]:
            try:
                total = sum(periods[x]["v"][m] for x in s["parts"])
                close(total, periods[s["total"]]["v"][m], s.get("tol", 0.6), f"financials.json {cid} interim sum {m}",
                      " + ".join(s["parts"]) + " = " + s["total"])
            except KeyError as e:
                err(f"financials.json {cid} interim sum {m}: missing {e}")
    lat = f["latest"]
    for k in ("period", "organic_from"):
        if lat.get(k) and lat[k] not in periods:
            err(f"financials.json {cid}: latest.{k} {lat[k]!r} is not an interim period")
    if lat.get("status") not in model.STATUSES:
        err(f"financials.json {cid}: latest.status must be one of {model.STATUSES}")
    ytd = lat.get("ytd_order")
    if not isinstance(ytd, list):
        err(f"financials.json {cid}: latest.ytd_order must list the year-to-date periods for the Latest column; "
            f"use [] when there is none yet")
    elif any(x not in periods for x in ytd):
        err(f"financials.json {cid}: latest.ytd_order names a period that is not in interim.periods")
    elif [periods[x].get("end") or "" for x in ytd] != sorted((periods[x].get("end") or "" for x in ytd), reverse=True):
        err(f"financials.json {cid}: latest.ytd_order must run from the newest period to the oldest")

    # segments, outlook, charts
    for seg in f.get("segments", []):
        w = f"financials.json {cid} segments {seg.get('title')!r}"
        for s in [seg.get("src")] + seg.get("srcs", []):
            need(src, s, w)
        for c in seg["columns"]:
            if c.get("kind") not in model.KINDS:
                err(f"{w}: unknown kind for {c.get('key')}")
        if seg.get("share_of"):
            parts = [r.get(seg["share_of"]) for r in seg["rows"]]
            if None in parts or not num(seg.get("total")):
                err(f"{w}: share_of needs a total and a value in every row")
            else:
                close(sum(parts), seg["total"], seg.get("tol", 0.6), w, "rows add up to the total")
    o = f["outlook"]
    need(src, o.get("src"), f"financials.json {cid} outlook")
    if not DATE.match(str(o.get("as_of"))):
        err(f"financials.json {cid} outlook: as_of must be a date")
    for item in o["items"]:
        if item.get("change") not in model.CHANGES:
            err(f"financials.json {cid} outlook: unknown change {item.get('change')!r}")
        if item.get("src"):
            need(src, item["src"], f"financials.json {cid} outlook")
    if o.get("targets"):
        need(src, o["targets"].get("src"), f"financials.json {cid} targets")
    for ch in f.get("charts", []):
        for pt in ch["points"]:
            check_cell(src, pt[1:], f"financials.json {cid} chart {ch['title']!r} {pt[0]}", ch.get("kind"))


# ---------- 4. news ----------

def check_news(d, src):
    n, as_of, order = d["news"], d["meta"]["as_of"], d["companies"]["order"]
    ids, prev = set(), "9999"
    for item in n["news"]:
        w = f"news.json {item.get('id')!r}"
        if not SLUG.match(str(item.get("id"))) or item.get("id") in ids:
            err(f"{w}: id must be a unique lower-case slug")
        ids.add(item.get("id"))
        if not DATE.match(str(item.get("date"))) or len(item["date"]) != 10 or item["date"] > as_of:
            err(f"{w}: date must be YYYY-MM-DD, on or before {as_of}")
        elif item["date"] > prev:
            err(f"{w}: news must be listed newest first")
        else:
            prev = item["date"]
        if item.get("company") not in order + ["industry"]:
            err(f"{w}: unknown company {item.get('company')!r}")
        if item.get("type") not in n["types"]:
            err(f"{w}: unknown type {item.get('type')!r}")
        if not item.get("headline") or not item.get("summary"):
            err(f"{w}: needs a headline and a summary")
        if not item.get("sources"):
            err(f"{w}: needs at least one source")
        for s in item.get("sources", []):
            need(src, s, w)
    for c in n["calls"]:
        w = f"news.json call {c.get('company')} {c.get('date')}"
        if c.get("company") not in order:
            err(f"{w}: unknown company")
        if not DATE.match(str(c.get("date"))) or c["date"] > as_of:
            err(f"{w}: date must be on or before {as_of}")
        if not c.get("points") or not c.get("links") or not c.get("sources"):
            err(f"{w}: needs points, links and sources")
        for s in c.get("links", []) + c.get("sources", []):
            need(src, s, w)
    for c in n["earlier_calls"]:
        need(src, c.get("link"), f"news.json earlier call {c.get('company')} {c.get('date')}")
        if c.get("company") not in order:
            err(f"news.json earlier call {c.get('date')}: unknown company")
    for c in n["calendar"]:
        if not DATE.match(str(c.get("date"))) or len(c["date"]) != 10:
            err(f"news.json calendar {c.get('event')!r}: date must be YYYY-MM-DD; put unconfirmed timing in calendar_windows")
    for c in n["calendar"] + n["calendar_windows"]:
        need(src, c.get("src"), f"news.json calendar {c.get('event')!r}")
        if c.get("company") not in order:
            err(f"news.json calendar {c.get('event')!r}: unknown company")
        if c.get("kind") not in model.CALENDAR_KINDS:
            err(f"news.json calendar {c.get('event')!r}: kind must be one of {sorted(model.CALENDAR_KINDS)}")
    if not model.EARNINGS_TYPES <= set(n["types"]):
        err(f"news.json types: needs {sorted(model.EARNINGS_TYPES)}, the types shown on the TIC earnings news screen")


# ---------- 5. share prices ----------

MONTH = re.compile(r"^\d{4}-(0[1-9]|1[0-2])$")
MAX_MONTHLY_MOVE = 0.7  # a monthly move beyond this is far more likely a typing slip than a real return


def check_pairs(pairs, where, positive):
    """A list of [month, number] pairs in month order with no gap. Returns the months."""
    months = []
    if not isinstance(pairs, list):
        err(f"{where}: must be a list of [month, number] pairs")
        return months
    for pair in pairs:
        if not (isinstance(pair, list) and len(pair) == 2 and MONTH.match(str(pair[0])) and num(pair[1])):
            err(f"{where}: {pair!r} is not a [month, number] pair")
            return months
        if positive and pair[1] <= 0:
            err(f"{where} {pair[0]}: must be above zero")
        if months and pair[0] != stockindex.next_month(months[-1]):
            err(f"{where}: {pair[0]} does not follow {months[-1]}; months must run in order with no gap")
        months.append(pair[0])
    return months


def check_prices(d, src):
    px, order = d["prices"], d["companies"]["order"]
    w = "prices.json"
    before = len(errors)
    for k in ("base", "last"):
        if not MONTH.match(str(px.get(k))):
            err(f"{w}: {k} must be YYYY-MM")
            return
    if px["base"] >= px["last"]:
        err(f"{w}: base must be before last")
        return
    for k in ("last_date", "read_on"):
        if not DATE.match(str(px.get(k))) or len(px[k]) != 10:
            err(f"{w}: {k} must be YYYY-MM-DD")
    if str(px.get("last_date"))[:7] != px["last"] or str(px.get("last_date")) > d["meta"]["as_of"]:
        err(f"{w}: last_date must fall in the last month and not after the as-of date")
    if set(px["series"]) != set(order) or set(px["market_caps"]) != set(order):
        err(f"{w}: series and market_caps need exactly the companies in companies.json order")
        return
    for cid in order:
        s, ws = px["series"][cid], f"{w} {cid}"
        need(src, s.get("src"), ws)
        for k in ("symbol", "market", "currency"):
            if not s.get(k):
                err(f"{ws}: missing {k}")
        if s.get("price_dp") not in (0, 1, 2) or not num(s.get("last_close")) or s["last_close"] <= 0:
            err(f"{ws}: needs price_dp of 0, 1 or 2 and a last_close above zero")
        adj_months = check_pairs(s.get("adj"), f"{ws} adj", positive=True)
        if not adj_months or adj_months[-1] != px["last"]:
            err(f"{ws}: adj must end at {px['last']}")
        if s.get("ret") is not None:
            need(src, s.get("ret_src"), f"{ws} ret")
            check_pairs(s["ret"], f"{ws} ret", positive=False)
            adj = dict(s.get("adj") or [])
            for month, published in s["ret"]:
                prev = [m for m in adj if stockindex.next_month(m) == month]
                if month in adj and prev:
                    close((adj[month] / adj[prev[0]] - 1) * 100, published, stockindex.RET_TOLERANCE + 0.05,
                          f"{ws} ret {month}", "published return against the one from prices")
        mcap, wm = px["market_caps"][cid], f"{w} market_caps {cid}"
        need(src, mcap.get("src"), wm)
        values = mcap.get("values")
        if not isinstance(values, list) or not values:
            err(f"{wm}: needs at least one [month, USD billion] pair")
        else:
            for pair in values:
                if not (isinstance(pair, list) and len(pair) == 2 and MONTH.match(str(pair[0])) and num(pair[1])
                        and pair[1] > 0):
                    err(f"{wm}: {pair!r} is not a [month, USD billion] pair")
    if len(errors) > before:  # the indexes need clean inputs; report those problems first
        return
    try:
        result = stockindex.build(px, order)
    except (ValueError, KeyError, ZeroDivisionError) as e:
        err(f"{w}: the indexes cannot be computed: {e}")
        return
    for cid in order:
        for month, r in zip(result["months"], result["returns"][cid]):
            if r is not None and abs(r) > MAX_MONTHLY_MOVE:
                err(f"{w} {cid} {month}: a monthly return of {r * 100:.0f}% looks like a typing slip")
    for name in ("cap", "eq"):
        if result[name][0] != stockindex.BASE_LEVEL or min(result[name]) <= 0:
            err(f"{w}: the {name} index must start at {stockindex.BASE_LEVEL:g} and stay above zero")
    for month, weights in zip(result["months"], result["weights"]):
        if weights is not None and abs(sum(weights.values()) - 1) > 1e-9:
            err(f"{w} {month}: market-cap weights do not add up to 100%")


# ---------- 6. writing ----------

def strings(x, path=""):
    if isinstance(x, str):
        yield path, x
    elif isinstance(x, dict):
        for k, v in x.items():
            if k != "url":
                yield from strings(v, f"{path}.{k}" if path else k)
    elif isinstance(x, list):
        for i, v in enumerate(x):
            yield from strings(v, f"{path}[{i}]")


def check_writing(d):
    texts = []
    for name in ("meta", "companies", "financials", "news", "prices"):
        texts += [(f"{name}.json {p}", s) for p, s in strings(d[name])]
    texts += [(f"sources.json {sid}.title", s["title"]) for sid, s in d["sources"]["sources"].items()]
    for f in sorted(model.SCREENS.glob("*.html")):
        texts.append((f"screens/{f.name}", re.sub(r"<[^>]+>", " ", f.read_text(encoding="utf-8"))))
    for where, s in texts:
        is_title = where.startswith("sources.json")
        for pat in BANNED:
            if not is_title and re.search(pat, s, re.I):
                err(f"{where}: banned wording ({pat.strip(chr(92) + 'b')}). Say the plain thing instead")
        for m in QUOTED.finditer(s):
            if len(m.group(1).split()) >= 15:
                err(f"{where}: quotation of 15 words or more. Paraphrase, or quote a short phrase")
        if EMOJI.search(s):
            err(f"{where}: emoji or pictograph. Use words")


# ---------- 7. built pages ----------

class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.ids, self.links, self.problems = [], [], [], []

    def handle_starttag(self, tag, attrs):
        self.note(tag, attrs)
        if tag not in VOID:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.note(tag, attrs)

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if not self.stack or self.stack[-1] != tag:
            self.problems.append(f"</{tag}> closes <{self.stack[-1] if self.stack else 'nothing'}>")
            if tag in self.stack:
                while self.stack and self.stack.pop() != tag:
                    pass
        else:
            self.stack.pop()

    def note(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            self.ids.append(a["id"])
        if tag == "a":
            self.links.append(a)
        if tag in ("iframe", "img", "object", "embed"):
            self.problems.append(f"<{tag}> is not allowed; pages are self-contained")


def check_pages(d):
    files = [s["file"] for s in d["screens"]["screens"]]
    for s in d["screens"]["screens"]:
        for old in s.get("was", []):
            if old in files or old == "index.html":
                err(f"screens.json {s['id']}: was {old!r} is the name of a current page")
    out = {}
    for single in (False, True):
        try:
            out.update(build_static.build(d, single=single))
        except Exception as e:  # a broken template or renderer is a failed check, not a crash
            err(f"build ({'single' if single else 'pages'}): {type(e).__name__}: {e}")
    parsed = {}
    for name, html in out.items():
        if "{{" in html:
            err(f"site/{name}: an unfilled {{{{slot}}}} is left in the page")
        p = Page()
        p.feed(html)
        p.close()
        parsed[name] = p
        for prob in p.problems[:5]:
            err(f"site/{name}: {prob}")
        if p.stack:
            err(f"site/{name}: unclosed tags {p.stack[-3:]}")
        dup = sorted({i for i in p.ids if p.ids.count(i) > 1})
        if dup:
            err(f"site/{name}: duplicate ids {dup[:5]}")
        for i in p.ids:
            if not SLUG.match(i) or i in RESERVED_HASH or i.startswith("comment-"):
                err(f"site/{name}: id {i!r} must be a lower-case slug and not a reserved name")
    for name, p in parsed.items():
        ids = set(p.ids)
        for a in p.links:
            href = a.get("href", "")
            if href.startswith(("https://", "mailto:")):
                if a.get("target") == "_blank" and "noopener" not in a.get("rel", ""):
                    err(f"site/{name}: external link without rel=noopener: {href[:60]}")
                continue
            if href.startswith("http://") or not href:
                err(f"site/{name}: link must be https or internal: {href!r}")
                continue
            page, _, frag = href.partition("#")
            target = parsed.get(page) if page else p
            if target is None:
                err(f"site/{name}: link to a page that is not built: {href}")
            elif frag and frag not in (set(target.ids) if page else ids):
                err(f"site/{name}: link to a missing anchor: {href}")
    return out


